#!/usr/bin/env python3
"""Pack web/ into a C source of gzipped assets embedded in the firmware.

Usage: pack_www.py <web_dir> <out.c>

At boot the firmware copies these gzipped files into LittleFS (/www) whenever
the bundle id differs from what is stored there, and the web server serves
them from LittleFS. Embedding them in the app image means one OTA .bin updates
firmware and web UI together, and the UI survives a corrupted filesystem.

The output is only rewritten when its content changes, so builds stay
incremental. Gzip mtime is fixed to 0 so output is reproducible.
"""
import gzip
import hashlib
import os
import sys

MIME = {
    ".html": "text/html; charset=utf-8",
    ".css": "text/css; charset=utf-8",
    ".js": "application/javascript; charset=utf-8",
    ".svg": "image/svg+xml",
    ".json": "application/json",
    ".ico": "image/x-icon",
    ".png": "image/png",
}


def main() -> int:
    web_dir, out_path = sys.argv[1], sys.argv[2]
    names = sorted(
        n for n in os.listdir(web_dir)
        if os.path.isfile(os.path.join(web_dir, n)) and not n.startswith(".")
    )
    bundle = hashlib.sha256()
    lines = [
        "/* GENERATED by tools/pack_www.py from web/ - do not edit. */",
        "#include <stddef.h>",
        "#include <stdint.h>",
        "#include \"www_assets.h\"",
        "",
    ]
    table = []
    for i, name in enumerate(names):
        ext = os.path.splitext(name)[1].lower()
        if ext not in MIME:
            print(f"pack_www: skipping {name} (unknown type)", file=sys.stderr)
            continue
        with open(os.path.join(web_dir, name), "rb") as f:
            raw = f.read()
        gz = gzip.compress(raw, compresslevel=9, mtime=0)
        bundle.update(name.encode() + b"\0" + raw)
        body = ",".join(str(b) for b in gz)
        lines.append(f"static const uint8_t a{i}[{len(gz)}] = {{{body}}};")
        table.append(f'    {{"/{name}", "{MIME[ext]}", a{i}, {len(gz)}}},')
    lines.append("const www_asset_t www_assets[] = {")
    lines += table
    lines.append("};")
    lines.append(f"const size_t www_asset_count = {len(table)};")
    lines.append(f'const char www_bundle_id[] = "{bundle.hexdigest()[:16]}";')
    out = "\n".join(lines) + "\n"

    old = None
    if os.path.exists(out_path):
        with open(out_path, "r", encoding="utf-8") as f:
            old = f.read()
    if old != out:
        os.makedirs(os.path.dirname(out_path), exist_ok=True)
        with open(out_path, "w", encoding="utf-8") as f:
            f.write(out)
        print(f"pack_www: wrote {out_path} ({len(table)} files, bundle {bundle.hexdigest()[:16]})")
    return 0


if __name__ == "__main__":
    sys.exit(main())
